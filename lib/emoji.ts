/** Недавние эмодзи — только в памяти текущей вкладки. */
const recent: string[] = [];

export function pushRecent(emoji: string): void {
  const idx = recent.indexOf(emoji);
  if (idx >= 0) recent.splice(idx, 1);
  recent.unshift(emoji);
  if (recent.length > 24) recent.pop();
}

export function getRecent(): string[] {
  return [...recent];
}

/** Поиск: по ключевым словам и по названию категории. */
export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const words = q.split(/\s+/);
  const result = new Set<string>();

  for (const [emoji, keywords] of Object.entries(EMOJI_KEYWORDS)) {
    if (words.every((w) => keywords.includes(w))) result.add(emoji);
  }
  for (const cat of EMOJI_CATEGORIES) {
    if (words.every((w) => cat.label.toLowerCase().includes(w))) {
      cat.emojis.forEach((e) => result.add(e));
    }
  }
  return [...result].slice(0, 96);
}
